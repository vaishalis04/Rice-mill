const router = require("express").Router();
const Controller = require("../controllers/gate.controller");
const GatePassController = require("../controllers/gatePass.controller");
const { attachUser, authorize, authorizeRoleOrModule } = require("../middlewares/auth.middleware");
const { verifyAccessToken } = require("../helpers/jwt.helper");
const { uploadImage } = require("../helpers/multer.helper");

// Gate entry/exit, token & queue, driver photo capture (Module 1)
// "lab" is included because Quality's Sampling page needs to read gate
// entries at status 'waiting_sampling' to populate its picker.
// "purchase" is included because Purchase Orders' gate-entry picker reads
// from here too.
// "admin" is included because Admin > Gate Entry now attaches Entry Type /
// PO / SO details onto the tokens the Gate creates (see attachDetails).

// Admin side — attaches Entry Type + PO/SO + Challan/Expected Qty onto a
// token generated by the Gate. Allowed for the admin role AND for any user /
// custom role that has been granted the "Gate Entry (Admin)" page
// (permission code admin.gate_entry). Declared BEFORE the router-wide guard
// below so that page permission alone is enough to attach details.
router.post(
  "/attach-details",
  verifyAccessToken,
  attachUser,
  authorizeRoleOrModule(["admin"], [], { codes: ["admin.gate_entry"] }),
  Controller.attachDetails
);

// admin.gate_entry is also accepted here, READ-ONLY, so that page can list the
// gate entries it works on without opening up any other gate action.
router.use(verifyAccessToken, attachUser, authorizeRoleOrModule(["gate","warehouse","production","lab","purchase","weighbridge","admin"], ["gate","warehouse","production","lab","purchase","weighbridge"], { codes: ["admin.gate_entry"], readOnly: true }));

router.get("/",     Controller.getAll);
router.get("/available-vehicles", Controller.getAvailableVehicles);
// Must come before "/:id" — otherwise Express would treat "misc-items" as
// an :id value for getById.
router.get("/misc-items", Controller.getMiscItems);
// Gate Pass (ORIGINAL + ACCOUNTS copies), printable once a truck has checked
// out. Read-only. Two segments deep, so these can never be mistaken for the
// "/:id" route below.
router.get("/:id/gate-pass/data", GatePassController.getData);
router.get("/:id/gate-pass", GatePassController.pdf);
router.get("/:id",  Controller.getById);
router.post("/",    Controller.create);
router.put("/:id",  Controller.update);
router.delete("/:id", Controller.delete);
router.post("/checkin", Controller.checkIn);
router.post("/checkout", Controller.checkOut);
// Gate side — Vehicle + Driver (+ Driver Photo) only, prints a token.
router.post("/generatetoken", Controller.generateToken);
// (POST /attach-details is declared above, before the router-wide guard.)
// Empty trucks / miscellaneous-item trucks (entry_type = "other") only —
// skips the rest of the journey and marks the truck received at warehouse.
router.post("/send-to-warehouse", Controller.sendToWarehouse);
// Uploads a captured/chosen driver photo to disk and returns its URL — the
// URL (a short path, not the image itself) is what actually gets saved on
// the gate entry's driver_photo_url column.
router.post("/upload-photo", uploadImage.single("photo"), Controller.uploadPhoto);

module.exports = router;